#!/usr/bin/env python3
"""Writes the native strings of "Lock from other apps" (the Mac panel and the
iPhone sheet) from the app's own .arb files, so no text is copied by hand.

    python3 scripts/anywhere_native_strings.py           # write
    python3 scripts/anywhere_native_strings.py --check   # exit 1 on drift

Output: apple/Anywhere/Strings/<lang>.lproj/Anywhere.strings, one per .arb
language. Keys stay the .arb keys; ICU placeholders such as {name} become
positional %1$@ in the order the English text declares them. Swift reads them
through InkText (apple/Anywhere/InkText.swift), which lists the same keys.
"""

