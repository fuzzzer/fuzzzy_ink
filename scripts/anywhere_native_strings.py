def placeholder_order(english: dict, key: str) -> list:
    declared = english.get("@" + key, {}).get("placeholders", {})
    return list(declared.keys())


def to_native(text: str, order: list) -> str:
    # A literal % stays a literal % for String(format:).
    text = text.replace("%", "%%")
    for index, name in enumerate(order, start=1):
        text = text.replace("{" + name + "}", "%" + str(index) + "$@")
    return text


def escape(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
    )


def render(language: str, english: dict) -> str:
    source = json.loads((L10N / f"app_{language}.arb").read_text("utf-8"))
    lines = [
        "/* Generated by scripts/anywhere_native_strings.py from "
        f"lib/src/core/l10n/app_{language}.arb. Do not edit. */",
        "",
    ]
    for key in KEYS:
        if key not in source:
            raise SystemExit(f"{key} is missing in app_{language}.arb")
        value = to_native(source[key], placeholder_order(english, key))
        lines.append(f'"{key}" = "{escape(value)}";')
    return "\n".join(lines) + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    english = json.loads((L10N / "app_en.arb").read_text("utf-8"))
    drift = []
    for language in LANGUAGES:
        target = OUT / f"{language}.lproj" / "Anywhere.strings"
        wanted = render(language, english)
        current = target.read_text("utf-8") if target.exists() else None
        if current == wanted:
            continue
        if check:
            drift.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(wanted, "utf-8")
    if drift:
        print("Out of date, run scripts/anywhere_native_strings.py:", *drift)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
