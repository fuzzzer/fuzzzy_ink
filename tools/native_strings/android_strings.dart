// The Android strings of "Lock from other apps" (the native selection sheet
// and tile), generated from the app's own .arb files so the two languages
// never drift and nothing is copied by hand (RESEARCH native code rule 9).
//
//   fvm dart run tools/native_strings/android_strings.dart          write
//   fvm dart run tools/native_strings/android_strings.dart --check  compare only
//
// It exports every key that starts with [sheetPrefix] plus the app's own
// wording listed in [reusedKeys], into
// android/app/src/main/res/values{,-ka}/anywhere_strings.xml.
import 'dart:convert';
import 'dart:io';

const sheetPrefix = 'anywhereSheet';

