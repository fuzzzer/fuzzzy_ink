const _arbFolder = 'lib/src/core/l10n';
const _resFolder = 'android/app/src/main/res';

/// Locale → the values folder it is written to.
const outputs = {
  'en': '$_resFolder/values/anywhere_strings.xml',
  'ka': '$_resFolder/values-ka/anywhere_strings.xml',
};

/// The keys exported from [arb], in the .arb file's order.
List<String> exportedKeys(Map<String, Object?> arb) => [
      for (final key in arb.keys)
        if (!key.startsWith('@') &&
            (key.startsWith(sheetPrefix) || reusedKeys.contains(key)))
          key,
    ];

/// One Android string resource file for [arb]: `{name}` placeholders become
/// positional `%1$s` arguments in the order they first appear in
/// [template] (the English text), so both languages take the same
/// arguments.
String androidStrings(Map<String, Object?> arb, Map<String, Object?> template) {
  final keys = exportedKeys(template);
  final missing = [
    for (final key in keys)
      if (arb[key] is! String) key,
    for (final key in reusedKeys)
      if (!template.containsKey(key)) key,
  ];
  if (missing.isNotEmpty) {
    throw FormatException('missing in the .arb file: ${missing.join(', ')}');
  }
  final buffer = StringBuffer()
    ..writeln('<?xml version="1.0" encoding="utf-8"?>')
    ..writeln(
      '<!-- Generated by tools/native_strings/android_strings.dart from '
      'lib/src/core/l10n/*.arb. Do not edit by hand. -->',
    )
    ..writeln('<resources>');
  for (final key in keys) {
    final names = _placeholders(template[key]! as String);
    final value = _escape(arb[key]! as String, names);
    buffer.writeln('    <string name="$key">$value</string>');
  }
  buffer.writeln('</resources>');
  return buffer.toString();
}

List<String> _placeholders(String text) {
  if (text.contains(RegExp(r'\{[^}]*,'))) {
    throw FormatException('plural or select is not supported: $text');
  }
  final names = <String>[];
  for (final match in RegExp(r'\{(\w+)\}').allMatches(text)) {
    final name = match.group(1)!;
    if (!names.contains(name)) names.add(name);
  }
  return names;
}

String _escape(String text, List<String> placeholders) {
  var value = text
      .replaceAll(r'\', r'\\')
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
      .replaceAll('"', r'\"')
      .replaceAll("'", r"\'")
      .replaceAll('\n', r'\n')
      // Only a string with arguments is formatted: there a literal % is %%.
      .replaceAll('%', placeholders.isEmpty ? r'\u0025' : '%%');
  for (var i = 0; i < placeholders.length; i++) {
    value = value.replaceAll('{${placeholders[i]}}', '%${i + 1}\$s');
  }
  if (value.startsWith('@') || value.startsWith('?')) value = '\\$value';
  return value;
}

Map<String, Object?> readArb(String locale) =>
    jsonDecode(File('$_arbFolder/app_$locale.arb').readAsStringSync())
        as Map<String, Object?>;

/// Every output file and what it should hold.
Map<String, String> expectedFiles() {
  final template = readArb('en');
  return {
    for (final MapEntry(key: locale, value: path) in outputs.entries)
      path: androidStrings(readArb(locale), template),
  };
}

void main(List<String> arguments) {
  final isCheck = arguments.contains('--check');
  var isStale = false;
  for (final MapEntry(key: path, value: content) in expectedFiles().entries) {
    final file = File(path);
    if (isCheck) {
      if (!file.existsSync() || file.readAsStringSync() != content) {
        stderr.writeln(
            '$path is stale: run tools/native_strings/android_strings.dart');
        isStale = true;
      }
    } else {
      file
        ..createSync(recursive: true)
        ..writeAsStringSync(content);
      stdout.writeln('wrote $path');
    }
  }
  if (isStale) exitCode = 1;
}
