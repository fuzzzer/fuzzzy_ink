// The Mac and iPhone strings of "Lock from other apps" (the Mac panel and
// the iPhone sheet, apple/Anywhere), generated from the app's own .arb files
// so the two languages never drift and nothing is copied by hand (RESEARCH
// native code rule 9). The Android twin is android_strings.dart.
//
//   fvm dart run tools/native_strings/apple_strings.dart          write
//   fvm dart run tools/native_strings/apple_strings.dart --check  compare only
//
// It exports every key that starts with [nativePrefix] plus the wording
// listed in [reusedKeys] (the app's own, and the Android sheet's where the
// Apple sheets say the same), into
// apple/Anywhere/Strings/<locale>.lproj/Anywhere.strings. Swift reads them
// through InkText (apple/Anywhere/InkText.swift).
