const _arbFolder = 'lib/src/core/l10n';

/// Locale → the strings file it is written to.
const outputs = {
  'en': 'apple/Anywhere/Strings/en.lproj/Anywhere.strings',
  'ka': 'apple/Anywhere/Strings/ka.lproj/Anywhere.strings',
};

/// The keys exported from [arb], in the .arb file's order.
List<String> exportedKeys(Map<String, Object?> arb) => [
      for (final key in arb.keys)
        if (!key.startsWith('@') &&
            (key.startsWith(nativePrefix) || reusedKeys.contains(key)))
          key,
    ];

/// One Apple `.strings` file for [arb]: `{name}` placeholders become
/// positional `%1$@` arguments in the order they first appear in
/// [template] (the English text), so both languages take the same
/// arguments.
String appleStrings(Map<String, Object?> arb, Map<String, Object?> template) {
  final keys = exportedKeys(template);
  final missing = [
    for (final key in keys)
      if (arb[key] is! String) key,
    for (final key in reusedKeys)
      if (!template.containsKey(key)) key,
  ];
  if (missing.isNotEmpty) {
    throw FormatException('missing in the .arb file: ${missing.join(', ')}');
  }
  final buffer = StringBuffer()
    ..writeln(
      '/* Generated by tools/native_strings/apple_strings.dart from '
      'lib/src/core/l10n/*.arb. Do not edit by hand. */',
    )
    ..writeln();
  for (final key in keys) {
    final names = _placeholders(_plain(template[key]! as String));
    buffer
        .writeln('"$key" = "${_escape(_plain(arb[key]! as String), names)}";');
  }
  return buffer.toString();
}

/// A whole-string select (the app's "Use fingerprint or face", which names
/// the phone's own quick unlock) as its `other` wording: the sheet does not
/// ask the phone which one it has.
String _plain(String text) {
  final select =
      RegExp(r'^\{\w+, select, .*\bother\{([^{}]*)\}\}$').firstMatch(text);
  return select == null ? text : select.group(1)!;
}

List<String> _placeholders(String text) {
  if (text.contains(RegExp(r'\{[^}]*,'))) {
    throw FormatException('plural or select is not supported: $text');
  }
  final names = <String>[];
  for (final match in RegExp(r'\{(\w+)\}').allMatches(text)) {
    final name = match.group(1)!;
    if (!names.contains(name)) names.add(name);
  }
  return names;
}

String _escape(String text, List<String> placeholders) {
  var value = text
      .replaceAll(r'\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll('\n', r'\n')
      // Only a string with arguments goes through String(format:): there a
      // literal % is %%.
      .replaceAll('%', placeholders.isEmpty ? '%' : '%%');
  for (var i = 0; i < placeholders.length; i++) {
    value = value.replaceAll('{${placeholders[i]}}', '%${i + 1}\$@');
  }
  return value;
}

Map<String, Object?> readArb(String locale) =>
    jsonDecode(File('$_arbFolder/app_$locale.arb').readAsStringSync())
        as Map<String, Object?>;

/// Every output file and what it should hold.
Map<String, String> expectedFiles() {
  final template = readArb('en');
  return {
    for (final MapEntry(key: locale, value: path) in outputs.entries)
      path: appleStrings(readArb(locale), template),
  };
}

void main(List<String> arguments) {
  final isCheck = arguments.contains('--check');
  var isStale = false;
  for (final MapEntry(key: path, value: content) in expectedFiles().entries) {
    final file = File(path);
    if (isCheck) {
      if (!file.existsSync() || file.readAsStringSync() != content) {
        stderr.writeln(
          '$path is stale: run tools/native_strings/apple_strings.dart',
        );
        isStale = true;
      }
    } else {
      file
        ..createSync(recursive: true)
        ..writeAsStringSync(content);
      stdout.writeln('wrote $path');
    }
  }
  if (isStale) exitCode = 1;
}
